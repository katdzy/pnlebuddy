import { readFile } from "node:fs/promises";
import { join } from "node:path";
import { marked } from "marked";
import type { Metadata } from "next";
import { notFound } from "next/navigation";
import { TopicScreen } from "@/components/topic/TopicScreen";
import { getTopic, TOPICS } from "@/content/taxonomy";

export function generateStaticParams() {
  return TOPICS.map((t) => ({ topicId: t.id }));
}

export async function generateMetadata({ params }: PageProps<"/topics/[topicId]">): Promise<Metadata> {
  const { topicId } = await params;
  return { title: getTopic(topicId)?.name ?? "Topic" };
}

/** Reviewer notes live in content/reviewers/<topic-id>.md (Markdown). */
async function loadReviewer(topicId: string): Promise<string | null> {
  "use cache";
  try {
    const md = await readFile(join(process.cwd(), "content", "reviewers", `${topicId}.md`), "utf8");
    return await marked.parse(md, { gfm: true });
  } catch {
    return null;
  }
}

type ReadingRef = { file: string; label: string; pages: number[] };

/**
 * Where each topic shows up in her own files. Generated by `npm run ingest` and
 * git-ignored (it names her paid materials), so a fresh clone builds without it.
 */
async function loadReading(topicId: string): Promise<ReadingRef[]> {
  "use cache";
  try {
    const all = JSON.parse(await readFile(join(process.cwd(), "src", "content", "generated", "reading.json"), "utf8"));
    return (all as Record<string, ReadingRef[]>)[topicId] ?? [];
  } catch {
    return [];
  }
}

export default async function TopicPage({ params }: PageProps<"/topics/[topicId]">) {
  const { topicId } = await params;
  if (!getTopic(topicId)) notFound();
  const html = await loadReviewer(topicId);
  const refs = await loadReading(topicId);
  return <TopicScreen topicId={topicId} reviewerHtml={html} reading={refs} />;
}
